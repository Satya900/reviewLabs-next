// app/mock-interview/results/[sessionId]/page.tsx
"use client";

import { use, useEffect, useState } from "react";
import Link from "next/link";
import { MockSessionResult } from "../../play/MockRunner";
import DifficultyBadge from "@/components/challenge/DifficultyBadge";
import CategoryTag from "@/components/challenge/CategoryTag";
import { Award, Clock, ArrowRight, Copy, CheckCircle, XCircle } from "lucide-react";
import { TwitterIcon } from "@/components/shared/SocialIcons";

interface PageProps {
  params: Promise<{ sessionId: string }>;
}

export default function MockResultsPage({ params }: PageProps) {
  const { sessionId } = use(params);
  const [result, setResult] = useState<MockSessionResult | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const data = localStorage.getItem(`mock_result_${sessionId}`);
    if (data) {
      try {
        setResult(JSON.parse(data));
      } catch (e) {
        console.error(e);
      }
    }
  }, [sessionId]);

  const copyLink = () => {
    if (typeof window === "undefined") return;
    navigator.clipboard.writeText(window.location.href);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const getTwitterUrl = () => {
    if (!result) return "";
    const text = `I scored ${result.score}/3 on the ReviewLabs AI Code Review Mock Interview! Catching the bugs that Copilot & ChatGPT leave behind. Try it yourself here:`;
    return `https://twitter.com/intent/tweet?text=${encodeURIComponent(text)}&url=${encodeURIComponent(
      typeof window !== "undefined" ? window.location.origin + "/mock-interview" : ""
    )}`;
  };

  if (!result) {
    return (
      <div className="w-full max-w-md mx-auto px-4 py-24 text-center space-y-4">
        <h2 className="text-xl font-sans font-bold text-txt-primary tracking-tight">Mock Session Not Found</h2>
        <p className="text-xs text-txt-secondary leading-relaxed font-sans-humanist">
          Ensure you completed the interview session or that you are on the same browser where you completed it.
        </p>
        <Link
          href="/mock-interview"
          className="inline-block text-xs font-sans font-semibold text-txt-primary hover:underline"
        >
          Return to Mock Interview
        </Link>
      </div>
    );
  }

  // Find weak spot category
  const wrongAttempts = result.attempts.filter((a) => !a.isCorrect);
  let weakSpot = "none";
  if (wrongAttempts.length > 0) {
    const counts: Record<string, number> = {};
    wrongAttempts.forEach((w) => {
      counts[w.category] = (counts[w.category] || 0) + 1;
    });
    weakSpot = Object.keys(counts).reduce((a, b) => (counts[a] > counts[b] ? a : b));
  }

  const minutes = Math.floor(result.timeSeconds / 60);
  const seconds = result.timeSeconds % 60;
  const timeFormatted = `${minutes}m ${seconds}s`;

  return (
    <div className="w-full max-w-3xl mx-auto px-4 md:px-6 py-16 space-y-10 select-none">
      {/* 1. Score Display */}
      <div className="p-8 border border-border-subt bg-surface-card rounded-lg text-center space-y-5">
        <div className="p-3 bg-black/[0.05] text-txt-primary border border-border-subt rounded-full w-fit mx-auto">
          <Award className="w-8 h-8 text-accent-text" />
        </div>
        <div className="space-y-2">
          <span className="text-[10px] font-sans font-bold text-txt-tertiary uppercase tracking-widest block">
            Mock Interview Score
          </span>
          <h1 className="font-display text-5xl sm:text-6xl text-txt-primary">
            {result.score} / 3
          </h1>
        </div>
        <p className="text-sm text-txt-secondary leading-relaxed max-w-sm mx-auto font-sans-humanist">
          {result.score === 3
            ? "Amazing! You have perfect AI-bug pattern recognition. Ready for production PR reviews."
            : result.score === 2
            ? "Good job! You caught most bugs, but missed a crucial edge case. Study the explanations below."
            : "Reviewing code generated by AI requires practice. Check out the resources below to improve."}
        </p>

        <div className="flex justify-center gap-6 text-xs text-txt-secondary border-t border-border-subt pt-5 max-w-xs mx-auto">
          <div className="flex items-center gap-1.5 font-medium font-sans-humanist">
            <Clock className="w-4 h-4 text-accent-text" />
            Total Time: <span className="font-bold text-txt-primary font-mono">{timeFormatted}</span>
          </div>
        </div>
      </div>

      {/* Weak Spot Callout */}
      {weakSpot !== "none" && (
        <div className="p-5 rounded-lg bg-danger-subtle border border-[#dc2626]/20 text-xs text-txt-secondary leading-relaxed flex items-center gap-3 font-sans-humanist">
          <span className="p-1.5 rounded bg-white/60 text-danger-text border border-[#dc2626]/25 font-bold uppercase tracking-widest text-[9px]">
            Weak Spot
          </span>
          <div>
            Your weak spot in this mock session: <strong className="text-txt-primary capitalize">{weakSpot.replace("-", " ")}</strong>. Try reviewing challenges in this category to sharpen your heuristics.
          </div>
        </div>
      )}

      {/* 2. Challenge Attempt Breakdown */}
      <div className="space-y-5">
        <h3 className="text-[10px] font-sans font-bold text-txt-primary uppercase tracking-widest border-b border-border-subt pb-3">
          Attempted Snippets
        </h3>

        <div className="space-y-4">
          {result.attempts.map((attempt, index) => (
            <div
              key={index}
              className="p-5 border border-border-subt rounded-lg bg-surface-card flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4"
            >
              <div className="space-y-2">
                <div className="flex flex-wrap items-center gap-2">
                  <span className="text-xs font-mono font-bold text-txt-tertiary">#0{index + 1}</span>
                  <DifficultyBadge difficulty={attempt.difficulty as any} />
                  <CategoryTag category={attempt.category as any} showIcon={false} />
                </div>
                <h4 className="text-sm font-sans font-bold text-txt-primary leading-snug tracking-tight">
                  {attempt.title}
                </h4>
                <p className="text-[11px] text-txt-tertiary flex items-center gap-1 font-sans-humanist">
                  <Clock className="w-3.5 h-3.5" /> Time taken:{" "}
                  <span className="font-mono font-bold text-txt-secondary">{attempt.timeTaken} seconds</span>
                </p>
              </div>

              <div className="flex items-center gap-4 w-full sm:w-auto justify-between sm:justify-end border-t border-border-subt sm:border-t-0 pt-4 sm:pt-0">
                <div className="flex items-center gap-1.5 text-xs font-semibold">
                  {attempt.isCorrect ? (
                    <>
                      <CheckCircle className="w-4 h-4 text-success" />
                      <span className="text-success">Correct</span>
                    </>
                  ) : (
                    <>
                      <XCircle className="w-4 h-4 text-danger" />
                      <span className="text-danger">Wrong</span>
                    </>
                  )}
                </div>

                <Link
                  href={`/challenges/${attempt.slug}`}
                  className="flex items-center gap-1 text-xs font-bold text-txt-primary hover:underline font-sans"
                >
                  View Details
                  <ArrowRight className="w-3.5 h-3.5" />
                </Link>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* 3. Action / Share Buttons */}
      <div className="flex flex-col sm:flex-row items-center gap-4 select-none">
        <Link
          href="/mock-interview"
          className="w-full sm:w-auto text-center px-6 h-10 flex items-center justify-center rounded-full text-xs font-semibold bg-accent hover:bg-accent-hover text-txt-inverse transition-colors active:scale-95 [box-shadow:var(--shadow-soft)]"
        >
          Try Again
        </Link>
        <div className="flex items-center gap-3 w-full sm:w-auto">
          <a
            href={getTwitterUrl()}
            target="_blank"
            rel="noopener noreferrer"
            className="flex-grow sm:flex-grow-0 flex items-center justify-center gap-1.5 px-4 h-10 border border-border-subt bg-surface-elevated hover:bg-surface hover:border-border-def text-xs font-sans font-medium rounded-full transition-colors text-txt-secondary hover:text-txt-primary"
          >
            <TwitterIcon className="w-4 h-4 text-[#62aef0]" />
            Share on X
          </a>
          <button
            onClick={copyLink}
            className="flex-grow sm:flex-grow-0 flex items-center justify-center gap-1.5 px-4 h-10 border border-border-subt bg-surface-elevated hover:bg-surface hover:border-border-def text-xs font-sans font-medium rounded-full transition-colors text-txt-secondary hover:text-txt-primary cursor-pointer"
          >
            <Copy className="w-4 h-4" />
            {copied ? "Copied!" : "Copy Link"}
          </button>
        </div>
      </div>
    </div>
  );
}
